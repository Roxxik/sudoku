// Solve-log backend client. Posts a solved game to the Cloudflare Worker
// (see docs/backend-prototype.md), now with offline durability: a failed or
// offline POST is queued in a localStorage outbox and retried -- lazily on the
// next solve (batched with it over the already batch-capable endpoint), on the
// `online` event, and once on load. Re-sends are idempotent server-side
// (solve_id + INSERT OR IGNORE), so an over-eager retry just writes nothing.
//
// Failures that reach the server but are rejected (a 4xx that isn't auth, or a
// 5xx) -- and solves that fail client-side validation -- are also reported to a
// sibling /errors endpoint, so the rejected payload is inspectable in the backend
// without touching the device. Offline (network-reject) failures aren't reported:
// there is no network to report over, they just stay queued for the next retry.
//
// This module also syncs the player's MOVE TIMELINE (recordMoves -> /moves), not
// just the final solve: whole-timeline snapshots are uploaded periodically during
// play and on close so an abandoned or in-progress puzzle is still captured. That
// path has its own coalescing outbox; see the Move-log outbox section below.

// Build-time source commit (short HEAD, '-dirty' for a modified tree, or
// "unknown" off-git). Generated by the Trunk pre_build hook, gitignored. Sent
// as client_version so a row can be traced to the exact frontend that wrote it.
import VERSION from "./version.js";

// Worker endpoint + shared key, generated into the gitignored backend-config.js
// by a Trunk pre_build hook (see Trunk.toml). Defaults are the production
// placeholders; SUDOKU_BACKEND_ENDPOINT / SUDOKU_API_KEY in the build env
// override them, so scripts/dev-local retargets the build at a local worker with
// no source edit. Both are public in the shipped bundle by necessity: there is
// no server-side render to inject them, and the key only buys a speed bump
// against drive-by bots (a human with devtools can read it). Public-writable.
import { ENDPOINT, API_KEY } from "./backend-config.js";

// Per-POST console logging is gated on cheat/debug mode (cheat.js): on by default
// on private/dev hosts (localhost + LAN, so dev-local logs for free) and off on
// the public site unless explicitly flipped on -- keeps end users' consoles quiet
// while staying available for debugging prod.
import { cheatOn } from "./cheat.js";

// The user's explicit opt-in to data sharing (Settings -> Share play data),
// default OFF. Posting is gated on this on TOP of CONFIGURED, so an opted-out
// user -- the default -- never enqueues or sends anything: no data leaves the
// device. settings.js is DOM-free, so importing it here is safe.
import { dataSharingOn } from "./settings.js";

// Shared "never swallow a storage failure" logger (see util.logStorageError).
import { logStorageError } from "./util.js";

// True until the constants above are replaced with the deployed values. While
// unconfigured we skip the POST entirely so the prototype doesn't fire a doomed
// request (and log a console error) on every solve before the backend exists.
const CONFIGURED = !ENDPOINT.includes("<subdomain>") && !API_KEY.includes("<paste");

// Posting requires BOTH a configured backend AND the user's opt-in. Checked at
// every enqueue and every flush, so flipping the setting off stops sends at once
// and a never-opted-in user queues nothing.
function postingEnabled() {
  return CONFIGURED && dataSharingOn();
}

// The failure-capture endpoint is the solve endpoint's sibling on the same
// worker: /solves -> /errors, same key. Derived here so the generated
// backend-config.js (and its build hook) needs no change.
const ERRORS_ENDPOINT = ENDPOINT.replace(/\/solves$/, "/errors");

// Outbox: a localStorage queue of unsent payloads. Bounded so a permanently
// unreachable backend can't grow it without limit (or blow the keepalive body
// cap); on overflow the OLDEST entries are dropped (a fresh solve is worth more
// than a long-stale one). Same try/catch-guarded idiom as store.js -- a quota or
// privacy-mode failure degrades to "this session isn't durable", never throws.
const OUTBOX_KEY = "sudoku.backend.outbox.v1";
const OUTBOX_MAX = 100;

function loadOutbox() {
  let raw;
  try { raw = localStorage.getItem(OUTBOX_KEY); } catch (err) { logStorageError("read", OUTBOX_KEY, err); return []; }
  if (!raw) return [];
  try {
    const entries = JSON.parse(raw);
    return Array.isArray(entries) ? entries : [];
  } catch (err) {
    logStorageError("read", OUTBOX_KEY, err);
    return [];
  }
}

function saveOutbox(entries) {
  try {
    localStorage.setItem(OUTBOX_KEY, JSON.stringify(entries));
  } catch (err) {
    // Quota or privacy mode: durability is best-effort; the solve flow is unaffected.
    logStorageError("write", OUTBOX_KEY, err);
  }
}

// Drop the given solve_ids from the outbox, re-reading current state first so a
// solve enqueued while a POST was in flight isn't clobbered by a stale snapshot.
function removeFromOutbox(ids) {
  const drop = new Set(ids);
  saveOutbox(loadOutbox().filter((e) => !drop.has(e.solve_id)));
}

// Mirror of the worker's valid(): a payload that would fail server validation is
// caught here so one bad entry can't 400 the whole batch (and block the good
// solves queued behind it). seed is optional; client_version is stamped by us.
function validPayload(s) {
  return !!s
    && typeof s.solve_id === "string" && s.solve_id.length > 0
    && typeof s.puzzle === "string"   && s.puzzle.length === 81
    && typeof s.solution === "string" && s.solution.length === 81
    && Number.isInteger(s.solve_ms)
    && (s.seed == null || typeof s.seed === "string");
}

// Best-effort failure report to /errors. Fire-and-forget, never throws, and has
// no outbox of its own -- a lost error report is simply lost (we never recurse
// failures into more failures). No keepalive: it's diagnostic, so we'd rather not
// stack its body against the solve POST under the shared keepalive size cap.
function reportFailure(detail) {
  if (!CONFIGURED) return;
  const debug = cheatOn();
  try {
    fetch(ERRORS_ENDPOINT, {
      method: "POST",
      headers: { "content-type": "application/json", "x-api-key": API_KEY },
      body: JSON.stringify({ ...detail, client_version: VERSION, user_agent: navigator.userAgent }),
    })
      .then((resp) => { if (debug) console.log(`[backend] error report -> ${resp.status}`); })
      .catch((err) => { if (debug) console.warn("[backend] error report failed:", err); });
  } catch (err) {
    if (debug) console.warn("[backend] error report threw:", err);
  }
}

// Capture a kept (retryable) failure at most once. Reports only the still-queued
// entries that haven't been flagged yet, then marks them, so a persistently 5xx
// batch retried on every solve/online/load doesn't spam /errors with duplicates.
function reportFailureOnce(ids, detail) {
  const current = loadOutbox();
  const inBatch = new Set(ids);
  const unreported = current.filter((e) => inBatch.has(e.solve_id) && !e.errorReported);
  if (!unreported.length) return;
  reportFailure({ ...detail, solves: unreported });
  for (const e of current) if (inBatch.has(e.solve_id)) e.errorReported = true;
  saveOutbox(current);
}

// A flush is in progress; serialize so the online/load triggers don't double-POST
// against a concurrent recordSolve. A request that arrives mid-flush sets
// flushAgain so the queue is re-checked once the current send settles.
let flushing = false;
let flushAgain = false;

// Send the whole outbox in one batch and reconcile the queue with the outcome:
//   2xx              -> delivered; drop the sent entries.
//   401              -> bad/missing key (visible in the dashboard, and the /errors
//                       endpoint would 401 too) -> keep, don't report; a corrected
//                       build picks the queue back up on reload.
//   other 4xx (400)  -> permanent client error -> capture the rejected payload to
//                       /errors, then drop so it can't wedge the queue forever.
//   5xx              -> transient server error -> keep for retry, capture once.
//   network reject   -> offline/unreachable -> keep for retry, don't report.
async function flushOutbox() {
  if (!postingEnabled()) return;
  if (flushing) { flushAgain = true; return; }
  const batch = loadOutbox();
  if (!batch.length) return;
  flushing = true;
  const debug = cheatOn();
  const sentIds = batch.map((e) => e.solve_id);
  try {
    const resp = await fetch(ENDPOINT, {
      method: "POST",
      headers: { "content-type": "application/json", "x-api-key": API_KEY },
      body: JSON.stringify({ solves: batch }),
      keepalive: true,
    });
    if (debug) {
      let body = "";
      try { body = await resp.text(); } catch {}
      console.log(`[backend] solves POST (${batch.length}) -> ${resp.status} ${body}`.trimEnd());
    }
    if (resp.ok) {
      removeFromOutbox(sentIds);
    } else if (resp.status === 401) {
      // Keep: don't lose solves to a deploy-time key mismatch; a fixed build delivers them.
    } else if (resp.status < 500) {
      reportFailure({ kind: "solve_post_rejected", status: resp.status, solves: batch });
      removeFromOutbox(sentIds);
    } else {
      reportFailureOnce(sentIds, { kind: "solve_post_server_error", status: resp.status });
    }
  } catch (err) {
    // Offline / network reject: keep for retry, nothing to report over.
    if (debug) console.warn("[backend] solves POST failed (queued for retry):", err);
  } finally {
    flushing = false;
    if (flushAgain) { flushAgain = false; flushOutbox(); }
  }
}

// Record a solved game. Enqueue-then-flush: the solve is persisted to the outbox
// FIRST (so it survives a closed tab or a never-resolving POST), then the whole
// queue is flushed in one batch. Fire-and-forget: recording a solve must never
// affect the solve flow, so this never throws and never awaits into the UI.
// `solve` is { solve_id, seed, puzzle, solution, solve_ms }.
export function recordSolve(solve) {
  if (!postingEnabled()) {
    if (cheatOn()) console.log(`[backend] solve not recorded: ${CONFIGURED ? "sharing off" : "backend not configured"}`);
    return;
  }
  const entry = { ...solve, client_version: VERSION };
  if (!validPayload(entry)) {
    // Would fail server validation -> don't poison the batch with it; capture it
    // instead so the malformed solve is still visible in the backend.
    if (cheatOn()) console.warn("[backend] solve failed client validation; not queued:", entry);
    reportFailure({ kind: "invalid_solve", solve: entry });
    return;
  }
  const outbox = loadOutbox();
  outbox.push(entry);
  saveOutbox(outbox.length > OUTBOX_MAX ? outbox.slice(outbox.length - OUTBOX_MAX) : outbox);
  flushOutbox();
}

// ---- Move-log outbox ----
// The player's move timeline (see tracker.js / play.js), synced periodically DURING
// play and on close -- not just at solve -- so an abandoned or in-progress puzzle
// still shows where people stalled. Unlike a solve (append-only, one row each) a
// move log is a whole-timeline SNAPSHOT that grows as play continues and is re-sent
// at each sync point, so this outbox COALESCES by solve_id: enqueuing a newer
// snapshot for a solve_id replaces the one already queued for it (latest wins),
// bounding the queue to one entry per puzzle in flight. The server upsert is
// idempotent and guarded against shrinking the stored log, so an over-eager or
// out-of-order retry is harmless. Sibling endpoint of /solves on the same worker.
const MOVES_ENDPOINT = ENDPOINT.replace(/\/solves$/, "/moves");
const MOVE_OUTBOX_KEY = "sudoku.backend.moves.outbox.v1";
const MOVE_OUTBOX_MAX = 50; // distinct puzzles; coalescing bounds per-puzzle growth

function loadMoveOutbox() {
  let raw;
  try { raw = localStorage.getItem(MOVE_OUTBOX_KEY); } catch (err) { logStorageError("read", MOVE_OUTBOX_KEY, err); return []; }
  if (!raw) return [];
  try {
    const entries = JSON.parse(raw);
    return Array.isArray(entries) ? entries : [];
  } catch (err) {
    logStorageError("read", MOVE_OUTBOX_KEY, err);
    return [];
  }
}

function saveMoveOutbox(entries) {
  try {
    localStorage.setItem(MOVE_OUTBOX_KEY, JSON.stringify(entries));
  } catch (err) {
    // Quota or privacy mode: durability is best-effort; the play flow is unaffected.
    logStorageError("write", MOVE_OUTBOX_KEY, err);
  }
}

// Drop delivered snapshots, KEEPING any that grew since they were sent: a snapshot
// re-enqueued by a sync that landed mid-flush carries more events than the one we
// delivered, so comparing event counts (not just solve_id) preserves it. Re-reads
// current state so a concurrent recordMoves isn't clobbered by a stale snapshot.
function removeDeliveredMoves(sent) {
  saveMoveOutbox(loadMoveOutbox().filter((e) => {
    const n = sent.get(e.solve_id);
    return n === undefined || (Array.isArray(e.events) && e.events.length > n);
  }));
}

// Mirror of the worker's validLog(): an in-progress timeline always carries at
// least its opening `session` event, so events is non-empty; seed is optional and
// client_version/last_t are stamped by recordMoves.
function validLog(s) {
  return !!s
    && typeof s.solve_id === "string" && s.solve_id.length > 0
    && typeof s.puzzle === "string"   && s.puzzle.length === 81
    && Array.isArray(s.events) && s.events.length > 0
    && (s.seed == null || typeof s.seed === "string");
}

let flushingMoves = false;
let flushMovesAgain = false;

// Send the whole move outbox in one batch and reconcile by event count:
//   2xx              -> delivered; drop sent snapshots, keep any that grew meanwhile.
//   401              -> bad/missing key -> keep; a corrected build picks them up.
//   other 4xx        -> permanent client error -> capture a COMPACT summary (not the
//                       full timelines -- they'd blow the /errors blob cap) and drop.
//   5xx              -> transient -> keep for retry. No once-report: move logs re-sync
//                       constantly, so a persistent 5xx would spam /errors; just keep.
//   network reject   -> offline/unreachable -> keep for retry, don't report.
async function flushMoveOutbox() {
  if (!postingEnabled()) return;
  if (flushingMoves) { flushMovesAgain = true; return; }
  const batch = loadMoveOutbox();
  if (!batch.length) return;
  flushingMoves = true;
  const debug = cheatOn();
  const sent = new Map(batch.map((e) => [e.solve_id, e.events.length]));
  try {
    const resp = await fetch(MOVES_ENDPOINT, {
      method: "POST",
      headers: { "content-type": "application/json", "x-api-key": API_KEY },
      body: JSON.stringify({ logs: batch }),
      keepalive: true,
    });
    if (debug) {
      let body = "";
      try { body = await resp.text(); } catch {}
      console.log(`[backend] moves POST (${batch.length}) -> ${resp.status} ${body}`.trimEnd());
    }
    if (resp.ok) {
      removeDeliveredMoves(sent);
    } else if (resp.status === 401) {
      // Keep: don't lose timelines to a deploy-time key mismatch.
    } else if (resp.status < 500) {
      reportFailure({
        kind: "moves_post_rejected",
        status: resp.status,
        logs: batch.map((e) => ({ solve_id: e.solve_id, event_count: e.events.length, last_t: e.last_t })),
      });
      removeDeliveredMoves(sent);
    } else {
      // 5xx: keep for the next retry; nothing reported (see header).
    }
  } catch (err) {
    if (debug) console.warn("[backend] moves POST failed (queued for retry):", err);
  } finally {
    flushingMoves = false;
    if (flushMovesAgain) { flushMovesAgain = false; flushMoveOutbox(); }
  }
}

// Record (sync) a move timeline snapshot for one puzzle. Enqueue-then-flush like
// recordSolve, but coalescing: a previously queued snapshot for the same solve_id
// is dropped in favour of this newer one. Fire-and-forget: never throws, never
// awaits into the UI. `log` is { solve_id, puzzle, seed, solved, events } where
// `events` is the full timeline array (tracker.snapshot()).
export function recordMoves(log) {
  if (!postingEnabled()) {
    if (cheatOn()) console.log(`[backend] moves not recorded: ${CONFIGURED ? "sharing off" : "backend not configured"}`);
    return;
  }
  const events = Array.isArray(log && log.events) ? log.events : [];
  const entry = {
    solve_id: log.solve_id,
    puzzle: log.puzzle,
    seed: log.seed ?? null,
    solved: !!log.solved,
    // Last event's solve-elapsed ms -- a progress signal the server stores without
    // parsing the timeline. Already integer ms in the tracker; round defensively.
    last_t: events.length ? Math.round(events[events.length - 1].t) : 0,
    events,
    client_version: VERSION,
  };
  if (!validLog(entry)) {
    if (cheatOn()) console.warn("[backend] move log failed client validation; not queued:", entry);
    return;
  }
  const outbox = loadMoveOutbox().filter((e) => e.solve_id !== entry.solve_id);
  outbox.push(entry);
  saveMoveOutbox(outbox.length > MOVE_OUTBOX_MAX ? outbox.slice(outbox.length - MOVE_OUTBOX_MAX) : outbox);
  flushMoveOutbox();
}

// ---- Daily-solve outbox ----
// The Puzzle-of-the-day Submit button. UNLIKE the solve/move feeds above, a daily
// submission is an EXPLICIT user act: tapping Submit means "post my time", so it
// bypasses the data-sharing opt-out (it gates on CONFIGURED alone, never on
// dataSharingOn) and is NOT dropped by clearOutboxes. It also drives a tri-state
// button -- Submit (active) -> Submit (disabled, queued) -> Submitted -- so beyond
// the pending outbox we keep a persistent set of ACCEPTED solve_ids: an outbox
// entry vanishes on delivery, but "Submitted" must survive that (and the session),
// so the done-set is where the final state lives. Sibling endpoint of /solves.
const DAILY_ENDPOINT = ENDPOINT.replace(/\/solves$/, "/daily");
const DAILY_OUTBOX_KEY = "sudoku.backend.daily.outbox.v1";
const DAILY_DONE_KEY = "sudoku.backend.daily.done.v1";
const DAILY_OUTBOX_MAX = 50; // distinct dailies in flight; coalesced per solve_id
// Only today's four dailies are ever queried (the overview shows one day), so the
// accepted set never needs to be large; bound it well above that and drop oldest.
const DAILY_DONE_MAX = 200;

// A daily submission posts regardless of the data-sharing setting -- the tap is the
// consent -- so it gates on a configured backend alone.
function dailyPostingEnabled() {
  return CONFIGURED;
}

function loadDailyOutbox() {
  let raw;
  try { raw = localStorage.getItem(DAILY_OUTBOX_KEY); } catch (err) { logStorageError("read", DAILY_OUTBOX_KEY, err); return []; }
  if (!raw) return [];
  try {
    const entries = JSON.parse(raw);
    return Array.isArray(entries) ? entries : [];
  } catch (err) {
    logStorageError("read", DAILY_OUTBOX_KEY, err);
    return [];
  }
}

function saveDailyOutbox(entries) {
  try {
    localStorage.setItem(DAILY_OUTBOX_KEY, JSON.stringify(entries));
  } catch (err) {
    // Quota or privacy mode: durability is best-effort; the play flow is unaffected.
    logStorageError("write", DAILY_OUTBOX_KEY, err);
  }
}

function loadDailyDone() {
  let raw;
  try { raw = localStorage.getItem(DAILY_DONE_KEY); } catch (err) { logStorageError("read", DAILY_DONE_KEY, err); return []; }
  if (!raw) return [];
  try {
    const ids = JSON.parse(raw);
    return Array.isArray(ids) ? ids : [];
  } catch (err) {
    logStorageError("read", DAILY_DONE_KEY, err);
    return [];
  }
}

function saveDailyDone(ids) {
  try {
    localStorage.setItem(DAILY_DONE_KEY, JSON.stringify(ids));
  } catch (err) {
    // Quota or privacy mode: tolerated like the other writes.
    logStorageError("write", DAILY_DONE_KEY, err);
  }
}

function removeFromDailyOutbox(ids) {
  const drop = new Set(ids);
  saveDailyOutbox(loadDailyOutbox().filter((e) => !drop.has(e.solve_id)));
}

// Mark solve_ids as accepted by the backend (the durable "Submitted" state),
// appending to the done-set and dropping the oldest past the cap. Idempotent.
function markDailyDone(ids) {
  const set = new Set(loadDailyDone());
  for (const id of ids) set.add(id);
  let arr = [...set];
  if (arr.length > DAILY_DONE_MAX) arr = arr.slice(arr.length - DAILY_DONE_MAX);
  saveDailyDone(arr);
}

// Mirror of the worker's validDaily(): (day, level) name the puzzle, seed optional,
// hints the dual score, client_version stamped by us.
function validDailyPayload(s) {
  return !!s
    && typeof s.solve_id === "string" && s.solve_id.length > 0
    && Number.isInteger(s.day)
    && Number.isInteger(s.level)
    && typeof s.puzzle === "string"   && s.puzzle.length === 81
    && Number.isInteger(s.solve_ms)
    && (s.seed == null || typeof s.seed === "string")
    && (s.hints == null || (Number.isInteger(s.hints) && s.hints >= 0));
}

// The submit state of one daily, by its solve_id, for the overview button:
//   "submitted" -> accepted by the backend (durable; in the done-set)
//   "pending"   -> queued for upload, not yet accepted (in the outbox)
//   "none"      -> never submitted
export function dailySubmitState(solve_id) {
  if (!solve_id) return "none";
  if (loadDailyDone().includes(solve_id)) return "submitted";
  if (loadDailyOutbox().some((e) => e.solve_id === solve_id)) return "pending";
  return "none";
}

// The daily-overview / win-screen buttons listen here so they can flip live as a
// submission queues and then lands -- without a global event bus. Set by home.js;
// invoked after any change to the daily outbox or done-set.
let dailyChangeListener = null;
export function setDailyChangeListener(cb) {
  dailyChangeListener = typeof cb === "function" ? cb : null;
}
function notifyDailyChange() {
  if (dailyChangeListener) {
    try { dailyChangeListener(); } catch {}
  }
}

let flushingDaily = false;
let flushDailyAgain = false;

// Send the daily outbox in one batch and reconcile:
//   2xx            -> accepted; move to the done-set (durable "Submitted") and drop.
//   401            -> bad/missing key -> keep; a corrected build delivers it.
//   other 4xx      -> permanent client error -> capture and drop.
//   5xx            -> transient -> keep for retry.
//   network reject -> offline/unreachable -> keep for retry, don't report.
// NOT gated on the data-sharing opt-out (see the section header): a submitted daily
// keeps retrying even with passive sharing off.
async function flushDailyOutbox() {
  if (!dailyPostingEnabled()) return;
  if (flushingDaily) { flushDailyAgain = true; return; }
  const batch = loadDailyOutbox();
  if (!batch.length) return;
  flushingDaily = true;
  const debug = cheatOn();
  const sentIds = batch.map((e) => e.solve_id);
  try {
    const resp = await fetch(DAILY_ENDPOINT, {
      method: "POST",
      headers: { "content-type": "application/json", "x-api-key": API_KEY },
      body: JSON.stringify({ solves: batch }),
      keepalive: true,
    });
    if (debug) {
      let body = "";
      try { body = await resp.text(); } catch {}
      console.log(`[backend] daily POST (${batch.length}) -> ${resp.status} ${body}`.trimEnd());
    }
    if (resp.ok) {
      markDailyDone(sentIds);
      removeFromDailyOutbox(sentIds);
      notifyDailyChange();
    } else if (resp.status === 401) {
      // Keep: don't lose a deliberate submission to a deploy-time key mismatch.
    } else if (resp.status < 500) {
      reportFailure({ kind: "daily_post_rejected", status: resp.status, solves: batch });
      removeFromDailyOutbox(sentIds);
      notifyDailyChange();
    } else {
      // 5xx: keep for the next retry; nothing reported.
    }
  } catch (err) {
    if (debug) console.warn("[backend] daily POST failed (queued for retry):", err);
  } finally {
    flushingDaily = false;
    if (flushDailyAgain) { flushDailyAgain = false; flushDailyOutbox(); }
  }
}

// Submit a solved daily for upload. Enqueue-then-flush like recordSolve, coalescing
// by solve_id so a double tap (or submitting from both the win screen and the
// overview) can't duplicate. Fire-and-forget: never throws, never awaits into the
// UI. `solve` is { solve_id, day, level, seed, puzzle, solution, solve_ms }.
export function recordDailySolve(solve) {
  if (!dailyPostingEnabled()) {
    if (cheatOn()) console.log("[backend] daily solve not recorded: backend not configured");
    return;
  }
  const entry = { ...solve, client_version: VERSION };
  if (!validDailyPayload(entry)) {
    if (cheatOn()) console.warn("[backend] daily solve failed client validation; not queued:", entry);
    reportFailure({ kind: "invalid_daily_solve", solve: entry });
    return;
  }
  // Already accepted -> idempotent no-op (don't re-queue a finished submission).
  if (loadDailyDone().includes(entry.solve_id)) return;
  const outbox = loadDailyOutbox().filter((e) => e.solve_id !== entry.solve_id);
  outbox.push(entry);
  saveDailyOutbox(outbox.length > DAILY_OUTBOX_MAX ? outbox.slice(outbox.length - DAILY_OUTBOX_MAX) : outbox);
  notifyDailyChange(); // reflect the pending state at once, before the POST resolves
  flushDailyOutbox();
}

// ---- Daily leaderboard read ----
// The READ side of the daily board (the writes are the outbox above). Reading the
// public, anonymous leaderboard is NOT "sharing your data", so -- unlike /solves --
// these gate on CONFIGURED alone, never on the data-sharing opt-out: an opted-out
// player still sees where the day's times landed. Both are awaited by the UI (they
// return data, not fire-and-forget) and never throw -- any failure (offline,
// unconfigured, a bad response) degrades to an empty/null result so the overview
// simply shows no board rather than breaking the page. The x-api-key header is the
// same speed-bump gate the writes use; it makes the GET preflight (cached a day).

// ---- Daily leaderboard read-through cache ----
// The reads below are cached in localStorage with a short TTL: within TTL of the
// last good fetch the cache is served directly (so reopening the page or revealing a
// rank doesn't re-hit the backend more than once every few minutes per day/level),
// and past the TTL a fresh fetch refreshes it. A fetch that FAILS (offline, a bad
// response) falls back to the last board the device saw -- at ANY age -- rather than
// going blank. A player who has since solved is spliced into that cached board by
// projectedStanding, so they still see where they'd land with no connection. Only the
// current day is ever rendered, so the cache is pruned to the most recent days.
const DAILY_BOARD_CACHE_KEY = "sudoku.backend.daily.board.cache.v1";
const DAILY_COUNTS_CACHE_KEY = "sudoku.backend.daily.counts.cache.v1";
const DAILY_CACHE_TTL_MS = 5 * 60 * 1000; // at most one fetch per 5 min, per day/level
const DAILY_CACHE_KEEP_DAYS = 2; // boards for older days are never displayed

// A cache slot is a flat object keyed by day ("<day>" for counts, "<day>:<level>"
// for boards). Load tolerates a missing/corrupt blob by returning an empty map.
function loadDailyCache(key) {
  let raw;
  try { raw = localStorage.getItem(key); } catch (err) { logStorageError("read", key, err); return {}; }
  if (!raw) return {};
  try {
    const map = JSON.parse(raw);
    return map && typeof map === "object" ? map : {};
  } catch (err) { logStorageError("read", key, err); return {}; }
}

// Write a map back, dropping every entry more than KEEP_DAYS behind `day` (the day
// just fetched) so the cache can't grow without bound. Best-effort; a quota error
// just skips the write (the live fetch already served the caller).
function saveDailyCache(key, map, day) {
  const kept = {};
  for (const [k, v] of Object.entries(map)) {
    const d = Number(k.split(":")[0]);
    if (Number.isFinite(d) && day - d <= DAILY_CACHE_KEEP_DAYS) kept[k] = v;
  }
  try { localStorage.setItem(key, JSON.stringify(kept)); } catch (err) { logStorageError("write", key, err); }
}

// Per-level solver counts for one puzzle-day: { level: n }. Drives the overview's
// pre-solve teaser ("N solved today"), which deliberately ships counts only, no
// times -- the times are the post-solve reward. Returns an object on success (a day
// with no solves yet is a real {}) or a fresh-enough / last-known cached copy, and
// NULL only when neither is available (unconfigured / offline with no cache) so the
// UI shows "unavailable" rather than passing off "no backend" as "be the first".
export async function fetchDailyCounts(day) {
  if (!CONFIGURED) return null;
  const cached = readDailyCountsCache(day, DAILY_CACHE_TTL_MS);
  if (cached) return cached; // within the TTL -> serve cache, skip the network
  const debug = cheatOn();
  try {
    const resp = await fetch(`${DAILY_ENDPOINT}?day=${encodeURIComponent(day)}`, {
      headers: { "x-api-key": API_KEY },
    });
    if (debug) console.log(`[backend] daily counts GET (day ${day}) -> ${resp.status}`);
    if (!resp.ok) return readDailyCountsCache(day);
    const body = await resp.json();
    const counts = body && body.counts && typeof body.counts === "object" ? body.counts : {};
    writeDailyCountsCache(day, counts);
    return counts;
  } catch (err) {
    if (debug) console.warn("[backend] daily counts GET failed:", err);
    return readDailyCountsCache(day);
  }
}

// Read the cached counts for a day. With `maxAgeMs` set, the entry counts only when
// younger than that (the TTL gate); without it, any age is returned (offline fall-back).
function readDailyCountsCache(day, maxAgeMs = Infinity) {
  const entry = loadDailyCache(DAILY_COUNTS_CACHE_KEY)[String(day)];
  if (!entry || !entry.counts || typeof entry.counts !== "object") return null;
  if (Date.now() - entry.ts > maxAgeMs) return null;
  return entry.counts;
}

function writeDailyCountsCache(day, counts) {
  const map = loadDailyCache(DAILY_COUNTS_CACHE_KEY);
  map[String(day)] = { ts: Date.now(), counts };
  saveDailyCache(DAILY_COUNTS_CACHE_KEY, map, day);
}

// The full ordered board for one (day, level): { count, times, hints, mine } in
// (hints, then time) rank order (anonymous -- the table stores no identity). When
// `solveId` is given, `mine` is the 0-based index of the caller's own row (or -1),
// so the caller can tell whether its solve is already on the board and avoid
// double-counting it when projecting a rank. Within the TTL the cached board is
// returned without a fetch; on a failed fetch the last cached board (any age) is
// returned; null only when there is nothing to show (the overview then teases).
export async function fetchDailyBoard(day, level, solveId) {
  if (!CONFIGURED) return null;
  const cached = readDailyBoardCache(day, level, solveId, DAILY_CACHE_TTL_MS);
  if (cached) return cached; // within the TTL -> serve cache, skip the network
  const debug = cheatOn();
  try {
    let qs = `day=${encodeURIComponent(day)}&level=${encodeURIComponent(level)}`;
    if (solveId) qs += `&solve_id=${encodeURIComponent(solveId)}`;
    const resp = await fetch(`${DAILY_ENDPOINT}?${qs}`, { headers: { "x-api-key": API_KEY } });
    if (debug) console.log(`[backend] daily board GET (day ${day}, level ${level}) -> ${resp.status}`);
    if (!resp.ok) return readDailyBoardCache(day, level, solveId);
    const body = await resp.json();
    if (!body || !Array.isArray(body.times)) return readDailyBoardCache(day, level, solveId);
    // `hints` parallels `times` (same rank order) -- the dual-score axis. Tolerate an
    // older worker that omits it (all-zero column) or `mine` (treat as not found).
    const hints = Array.isArray(body.hints) && body.hints.length === body.times.length
      ? body.hints
      : body.times.map(() => 0);
    const board = {
      count: typeof body.count === "number" ? body.count : body.times.length,
      times: body.times,
      hints,
      mine: Number.isInteger(body.mine) ? body.mine : -1,
    };
    writeDailyBoardCache(day, level, solveId, board);
    return board;
  } catch (err) {
    if (debug) console.warn("[backend] daily board GET failed:", err);
    return readDailyBoardCache(day, level, solveId);
  }
}

function boardCacheKey(day, level) {
  return `${day}:${level}`;
}

// Read the cached board for a (day, level). `maxAgeMs` gates by age as above. `mine`
// is solve-specific, so it is trusted only when the cache was taken for THIS solveId;
// otherwise it is reported as -1 and projectedStanding splices the player in locally.
function readDailyBoardCache(day, level, solveId, maxAgeMs = Infinity) {
  const entry = loadDailyCache(DAILY_BOARD_CACHE_KEY)[boardCacheKey(day, level)];
  if (!entry || !Array.isArray(entry.times)) return null;
  if (Date.now() - entry.ts > maxAgeMs) return null;
  const mine =
    solveId && entry.solveId === solveId && Number.isInteger(entry.mine) ? entry.mine : -1;
  return { count: entry.count, times: entry.times, hints: entry.hints, mine };
}

function writeDailyBoardCache(day, level, solveId, board) {
  const map = loadDailyCache(DAILY_BOARD_CACHE_KEY);
  map[boardCacheKey(day, level)] = {
    ts: Date.now(),
    solveId: solveId || null,
    count: board.count,
    times: board.times,
    hints: board.hints,
    mine: board.mine,
  };
  saveDailyCache(DAILY_BOARD_CACHE_KEY, map, day);
}

// Active eviction for the daily caches, run on load. saveDailyCache already prunes
// on every write, but a device that opens the app without visiting the daily page
// never triggers a write -- so without this, a board cached days ago would linger
// until the page is next opened. Drop every entry older than KEEP_DAYS by wall-clock
// (each entry carries its write `ts`), so the caches stay lean by reload, not just by
// next-use. Self-contained -- no puzzle-day index needed.
function pruneDailyCaches() {
  const maxAgeMs = DAILY_CACHE_KEEP_DAYS * 24 * 60 * 60 * 1000;
  const now = Date.now();
  for (const key of [DAILY_BOARD_CACHE_KEY, DAILY_COUNTS_CACHE_KEY]) {
    const map = loadDailyCache(key);
    const kept = {};
    let dropped = 0;
    for (const [k, v] of Object.entries(map)) {
      if (v && typeof v.ts === "number" && now - v.ts <= maxAgeMs) kept[k] = v;
      else dropped++;
    }
    if (dropped) {
      try {
        localStorage.setItem(key, JSON.stringify(kept));
      } catch (err) {
        logStorageError("write", key, err);
      }
    }
  }
}

// Forget everything queued for PASSIVE upload. Called when the user opts OUT of
// sharing (Settings -> Share play data) so "off" leaves nothing pending on the
// device -- not even a stale snapshot from a session when sharing was on. The daily
// outbox is deliberately NOT cleared: a daily submission is an explicit act the
// opt-out doesn't govern. Best-effort and quota-safe; clearing never affects play.
export function clearOutboxes() {
  try { localStorage.removeItem(OUTBOX_KEY); } catch (err) { logStorageError("delete", OUTBOX_KEY, err); }
  try { localStorage.removeItem(MOVE_OUTBOX_KEY); } catch (err) { logStorageError("delete", MOVE_OUTBOX_KEY, err); }
}

// Retry triggers beyond the lazy next-solve/next-sync flush: drain both queues when
// connectivity returns, and once on load (a tab opened fresh while already online
// sees no `online` transition, so without this a queue left by a previous session
// would sit until the next solve/sync). All no-op when unconfigured or empty.
if (typeof window !== "undefined") {
  window.addEventListener("online", () => { flushOutbox(); flushMoveOutbox(); flushDailyOutbox(); });
  flushOutbox();
  flushMoveOutbox();
  flushDailyOutbox();
  // Evict stale daily-leaderboard cache on load (see pruneDailyCaches).
  pruneDailyCaches();
}
